function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  const isPublic = !useMatches({
    select: (ms) => ms.some((m) => m.routeId.startsWith("/_authenticated")),
  });

  // Keep router + query caches in sync with sign-in / sign-out transitions.
  useEffect(() => {
    if (pendingConfirmationCallback() === "expired") router.navigate({ to: "/auth", replace: true });
    const {
      data: { subscription },
    } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      {isPublic && <SiteFooter />}
      <Toaster richColors position="top-center" toastOptions={{ classNames: { success: "!bg-notice !text-notice-foreground !border-notice" } }} />
    </QueryClientProvider>
  );
}
